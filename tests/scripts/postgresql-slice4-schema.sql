INSERT INTO "PA_TICKETS_ROLE_PERMISSION" ("N_ROLE_PERMISSION_ID", "N_ROLE_ID", "N_PERMISSION_ID")
SELECT COALESCE((SELECT MAX("N_ROLE_PERMISSION_ID") FROM "PA_TICKETS_ROLE_PERMISSION"), 0) + ROW_NUMBER() OVER (ORDER BY r."N_ROLE_ID", p."N_PERMISSION_ID"),
       r."N_ROLE_ID", p."N_PERMISSION_ID"
FROM "PA_TICKETS_ROLE" r CROSS JOIN "PA_TICKETS_PERMISSION" p
WHERE r."S_ROLE_CODE" = 'ADMINISTRATOR' AND p."S_PERMISSION_CODE" IN ('SLA_READ', 'SLA_ADMIN', 'SLA_PUBLISH', 'SLA_RETIRE')
  AND NOT EXISTS (SELECT 1 FROM "PA_TICKETS_ROLE_PERMISSION" rp WHERE rp."N_ROLE_ID" = r."N_ROLE_ID" AND rp."N_PERMISSION_ID" = p."N_PERMISSION_ID");
INSERT INTO "PA_TICKETS_ROLE_PERMISSION" ("N_ROLE_PERMISSION_ID", "N_ROLE_ID", "N_PERMISSION_ID")
SELECT COALESCE((SELECT MAX("N_ROLE_PERMISSION_ID") FROM "PA_TICKETS_ROLE_PERMISSION"), 0) + 1,
       r."N_ROLE_ID", p."N_PERMISSION_ID"
FROM "PA_TICKETS_ROLE" r CROSS JOIN "PA_TICKETS_PERMISSION" p
WHERE r."S_ROLE_CODE" = 'AUDITOR' AND p."S_PERMISSION_CODE" = 'SLA_READ'
  AND NOT EXISTS (SELECT 1 FROM "PA_TICKETS_ROLE_PERMISSION" rp WHERE rp."N_ROLE_ID" = r."N_ROLE_ID" AND rp."N_PERMISSION_ID" = p."N_PERMISSION_ID");
