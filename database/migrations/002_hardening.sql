CREATE TABLE PA_TICKETS_WORKFLOW_STEP_INSTANCE (
    N_STEP_INSTANCE_ID NUMBER(18) NOT NULL,
    N_WORKFLOW_INSTANCE_ID NUMBER(18) NOT NULL,
    N_WORKFLOW_STEP_ID NUMBER(18) NOT NULL,
    N_PARENT_STEP_INSTANCE_ID NUMBER(18),
    S_STATUS VARCHAR2(30) DEFAULT 'PENDING' NOT NULL,
    S_BRANCH_KEY VARCHAR2(200),
    S_CONDITION_RESULT VARCHAR2(100),
    N_WORK_ITEM_ID NUMBER(18),
    N_APPROVAL_ID NUMBER(18),
    D_STARTED_AT TIMESTAMP WITH TIME ZONE,
    D_COMPLETED_AT TIMESTAMP WITH TIME ZONE,
    D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    D_UPDATED_AT TIMESTAMP WITH TIME ZONE,
    CONSTRAINT PK_PA_TICKETS_WF_STEP_INST PRIMARY KEY (N_STEP_INSTANCE_ID),
    CONSTRAINT FK_PA_TICKETS_WFSI_INSTANCE FOREIGN KEY (N_WORKFLOW_INSTANCE_ID) REFERENCES PA_TICKETS_WORKFLOW_INSTANCE(N_WORKFLOW_INSTANCE_ID),
    CONSTRAINT FK_PA_TICKETS_WFSI_STEP FOREIGN KEY (N_WORKFLOW_STEP_ID) REFERENCES PA_TICKETS_WORKFLOW_STEP(N_WORKFLOW_STEP_ID),
    CONSTRAINT FK_PA_TICKETS_WFSI_PARENT FOREIGN KEY (N_PARENT_STEP_INSTANCE_ID) REFERENCES PA_TICKETS_WORKFLOW_STEP_INSTANCE(N_STEP_INSTANCE_ID),
    CONSTRAINT FK_PA_TICKETS_WFSI_WI FOREIGN KEY (N_WORK_ITEM_ID) REFERENCES PA_TICKETS_WORK_ITEM(N_WORK_ITEM_ID),
    CONSTRAINT FK_PA_TICKETS_WFSI_APPROVAL FOREIGN KEY (N_APPROVAL_ID) REFERENCES PA_TICKETS_APPROVAL(N_APPROVAL_ID),
    CONSTRAINT CK_PA_TICKETS_WFSI_STATUS CHECK (S_STATUS IN ('PENDING','ACTIVE','WAITING','COMPLETED','SKIPPED','CANCELLED'))
);

CREATE TABLE PA_TICKETS_WORKFLOW_STEP_INSTANCE_HISTORY (
    N_STEP_INSTANCE_HISTORY_ID NUMBER(18) NOT NULL,
    N_STEP_INSTANCE_ID NUMBER(18) NOT NULL,
    S_ACTION VARCHAR2(80) NOT NULL,
    S_OLD_STATUS VARCHAR2(30),
    S_NEW_STATUS VARCHAR2(30),
    S_REASON CLOB,
    N_ACTOR_USER_ID NUMBER(18),
    D_EVENT_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PA_TICKETS_WFSI_HIST PRIMARY KEY (N_STEP_INSTANCE_HISTORY_ID),
    CONSTRAINT FK_PA_TICKETS_WFSIH_INSTANCE FOREIGN KEY (N_STEP_INSTANCE_ID) REFERENCES PA_TICKETS_WORKFLOW_STEP_INSTANCE(N_STEP_INSTANCE_ID),
    CONSTRAINT FK_PA_TICKETS_WFSIH_USER FOREIGN KEY (N_ACTOR_USER_ID) REFERENCES PA_TICKETS_USER(N_USER_ID)
);

CREATE INDEX IX_PA_TICKETS_WFSI_INSTANCE ON PA_TICKETS_WORKFLOW_STEP_INSTANCE(N_WORKFLOW_INSTANCE_ID, S_STATUS);
