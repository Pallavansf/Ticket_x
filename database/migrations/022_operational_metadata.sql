DECLARE
    PROCEDURE create_sequence_if_missing(p_name VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_SEQUENCES WHERE SEQUENCE_NAME = UPPER(p_name);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'CREATE SEQUENCE ' || p_name || ' START WITH 1 INCREMENT BY 1 NOCACHE';
        END IF;
    END;
    PROCEDURE create_table_if_missing(p_name VARCHAR2, p_ddl CLOB) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = UPPER(p_name);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE p_ddl;
        END IF;
    END;
BEGIN
    create_sequence_if_missing('PA_TICKETS_STATUS_SEQ');
    create_sequence_if_missing('PA_TICKETS_STATUS_TRANSITION_SEQ');
    create_sequence_if_missing('PA_TICKETS_PRIORITY_SEQ');

    create_table_if_missing('PA_TICKETS_STATUS',
        'CREATE TABLE PA_TICKETS_STATUS (
            N_STATUS_ID NUMBER(18) NOT NULL,
            S_STATUS_CODE VARCHAR2(50) NOT NULL,
            S_STATUS_NAME VARCHAR2(100) NOT NULL,
            S_DESCRIPTION VARCHAR2(1000),
            N_IS_INITIAL NUMBER(1) DEFAULT 0 NOT NULL,
            N_IS_OPEN NUMBER(1) DEFAULT 1 NOT NULL,
            N_IS_CLOSED NUMBER(1) DEFAULT 0 NOT NULL,
            N_IS_CANCELLED NUMBER(1) DEFAULT 0 NOT NULL,
            N_DISPLAY_ORDER NUMBER(10) DEFAULT 0 NOT NULL,
            N_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
            N_ROW_VERSION NUMBER(10) DEFAULT 0 NOT NULL,
            D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            N_CREATED_BY NUMBER(18) NOT NULL,
            D_UPDATED_AT TIMESTAMP WITH TIME ZONE,
            N_UPDATED_BY NUMBER(18),
            CONSTRAINT PK_PA_TICKETS_STATUS PRIMARY KEY (N_STATUS_ID),
            CONSTRAINT UK_PA_TICKETS_STATUS_CODE UNIQUE (S_STATUS_CODE),
            CONSTRAINT CK_PA_TICKETS_STATUS_FLAGS CHECK (
                N_IS_INITIAL IN (0,1) AND N_IS_OPEN IN (0,1) AND
                N_IS_CLOSED IN (0,1) AND N_IS_CANCELLED IN (0,1) AND
                N_ACTIVE IN (0,1) AND N_ROW_VERSION >= 0
            )
        )');
    create_table_if_missing('PA_TICKETS_STATUS_TRANSITION',
        'CREATE TABLE PA_TICKETS_STATUS_TRANSITION (
            N_STATUS_TRANSITION_ID NUMBER(18) NOT NULL,
            S_FROM_STATUS_CODE VARCHAR2(50) NOT NULL,
            S_TO_STATUS_CODE VARCHAR2(50) NOT NULL,
            S_CONDITION VARCHAR2(2000),
            N_ALLOWED NUMBER(1) DEFAULT 1 NOT NULL,
            D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            N_CREATED_BY NUMBER(18) NOT NULL,
            CONSTRAINT PK_PA_TICKETS_STATUS_TRANSITION PRIMARY KEY (N_STATUS_TRANSITION_ID),
            CONSTRAINT UK_PA_TICKETS_STATUS_TRANSITION UNIQUE (S_FROM_STATUS_CODE, S_TO_STATUS_CODE),
            CONSTRAINT CK_PA_TICKETS_STATUS_TRANSITION_ALLOWED CHECK (N_ALLOWED IN (0,1)),
            CONSTRAINT FK_PA_TICKETS_ST_FROM FOREIGN KEY (S_FROM_STATUS_CODE) REFERENCES PA_TICKETS_STATUS(S_STATUS_CODE),
            CONSTRAINT FK_PA_TICKETS_ST_TO FOREIGN KEY (S_TO_STATUS_CODE) REFERENCES PA_TICKETS_STATUS(S_STATUS_CODE)
        )');
    create_table_if_missing('PA_TICKETS_PRIORITY',
        'CREATE TABLE PA_TICKETS_PRIORITY (
            N_PRIORITY_ID NUMBER(18) NOT NULL,
            S_PRIORITY_CODE VARCHAR2(30) NOT NULL,
            S_PRIORITY_NAME VARCHAR2(100) NOT NULL,
            S_DESCRIPTION VARCHAR2(1000),
            N_PRIORITY_LEVEL NUMBER(5) NOT NULL,
            N_DISPLAY_ORDER NUMBER(10) DEFAULT 0 NOT NULL,
            N_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
            N_IS_DEFAULT NUMBER(1) DEFAULT 0 NOT NULL,
            N_ROW_VERSION NUMBER(10) DEFAULT 0 NOT NULL,
            D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
            N_CREATED_BY NUMBER(18) NOT NULL,
            D_UPDATED_AT TIMESTAMP WITH TIME ZONE,
            N_UPDATED_BY NUMBER(18),
            CONSTRAINT PK_PA_TICKETS_PRIORITY PRIMARY KEY (N_PRIORITY_ID),
            CONSTRAINT UK_PA_TICKETS_PRIORITY_CODE UNIQUE (S_PRIORITY_CODE),
            CONSTRAINT CK_PA_TICKETS_PRIORITY_FLAGS CHECK (
                N_ACTIVE IN (0,1) AND N_IS_DEFAULT IN (0,1) AND N_ROW_VERSION >= 0
