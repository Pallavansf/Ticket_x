CREATE TABLE IF NOT EXISTS "PA_TICKETS_SLA_POLICY_DEFINITION" (
    "N_POLICY_ID" bigint PRIMARY KEY,
    "S_POLICY_CODE" varchar(100) NOT NULL UNIQUE,
    "S_POLICY_NAME" varchar(200) NOT NULL,
    "S_DESCRIPTION" varchar(2000),
    "N_ACTIVE" integer NOT NULL DEFAULT 1,
    "D_CREATED_AT" timestamp with time zone NOT NULL DEFAULT now(),
    "N_CREATED_BY" bigint NOT NULL,
    "N_ROW_VERSION" integer NOT NULL DEFAULT 0
);

ALTER TABLE "PA_TICKETS_SLA_POLICY"
    ADD COLUMN IF NOT EXISTS "N_CATEGORY_ID" bigint,
    ADD COLUMN IF NOT EXISTS "N_SUB_CATEGORY_ID" bigint,
    ADD COLUMN IF NOT EXISTS "S_STATUS" varchar(20) NOT NULL DEFAULT 'DRAFT',
    ADD COLUMN IF NOT EXISTS "D_CREATED_AT" timestamp with time zone NOT NULL DEFAULT now(),
    ADD COLUMN IF NOT EXISTS "N_CREATED_BY" bigint NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS "D_PUBLISHED_AT" timestamp with time zone,
    ADD COLUMN IF NOT EXISTS "N_PUBLISHED_BY" bigint,
    ADD COLUMN IF NOT EXISTS "D_RETIRED_AT" timestamp with time zone,
    ADD COLUMN IF NOT EXISTS "N_RETIRED_BY" bigint,
    ADD COLUMN IF NOT EXISTS "N_ROW_VERSION" integer NOT NULL DEFAULT 0;

UPDATE "PA_TICKETS_SLA_POLICY"
SET "S_STATUS" = 'PUBLISHED'
WHERE "N_ACTIVE" AND "S_STATUS" = 'DRAFT';

INSERT INTO "PA_TICKETS_SLA_POLICY_DEFINITION"
    ("N_POLICY_ID", "S_POLICY_CODE", "S_POLICY_NAME", "N_ACTIVE", "D_CREATED_AT", "N_CREATED_BY")
SELECT p."N_POLICY_ID", MAX(p."S_POLICY_CODE"), MAX(p."S_POLICY_CODE"), 1, now(), 0
FROM "PA_TICKETS_SLA_POLICY" p
WHERE NOT EXISTS (
    SELECT 1 FROM "PA_TICKETS_SLA_POLICY_DEFINITION" d WHERE d."N_POLICY_ID" = p."N_POLICY_ID")
GROUP BY p."N_POLICY_ID";

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'CK_PA_TICKETS_SLA_POLICY_STATUS'
          AND conrelid = '"PA_TICKETS_SLA_POLICY"'::regclass
    ) THEN
        ALTER TABLE "PA_TICKETS_SLA_POLICY"
            ADD CONSTRAINT "CK_PA_TICKETS_SLA_POLICY_STATUS"
                CHECK ("S_STATUS" IN ('DRAFT', 'PUBLISHED', 'RETIRED'));
    END IF;
END $$;

CREATE INDEX IF NOT EXISTS "IX_PA_TICKETS_SLA_POLICY_EFFECTIVE"
    ON "PA_TICKETS_SLA_POLICY" ("N_POLICY_ID", "S_STATUS", "D_EFFECTIVE_FROM", "D_EFFECTIVE_TO");
CREATE INDEX IF NOT EXISTS "IX_PA_TICKETS_SLA_POLICY_CATEGORY"
    ON "PA_TICKETS_SLA_POLICY" ("N_CATEGORY_ID", "N_SUB_CATEGORY_ID", "N_ACTIVE");

ALTER TABLE "PA_TICKETS_SLA_CALENDAR"
    ADD COLUMN IF NOT EXISTS "D_EFFECTIVE_FROM" timestamp with time zone NOT NULL DEFAULT now(),
    ADD COLUMN IF NOT EXISTS "D_EFFECTIVE_TO" timestamp with time zone,
    ADD COLUMN IF NOT EXISTS "N_ROW_VERSION" integer NOT NULL DEFAULT 0;

INSERT INTO "PA_TICKETS_PERMISSION" ("N_PERMISSION_ID", "S_PERMISSION_CODE", "S_PERMISSION_NAME", "N_ACTIVE")
