             SELECT 1 FROM PA_TICKETS_ROLE_PERMISSION rp
              WHERE rp.N_ROLE_ID = r.N_ROLE_ID AND rp.N_PERMISSION_ID = p.N_PERMISSION_ID)
    ) LOOP
