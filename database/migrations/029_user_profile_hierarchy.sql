DECLARE
    column_count NUMBER;
    index_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO column_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'PA_TICKETS_USER'
       AND COLUMN_NAME = 'N_EMAIL_VERIFIED';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PA_TICKETS_USER ADD (N_EMAIL_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL)';
    END IF;

    SELECT COUNT(*)
      INTO index_count
      FROM USER_INDEXES
     WHERE INDEX_NAME = 'UK_PA_TICKETS_USER_EMAIL_UPPER';

    IF index_count = 0 THEN
        EXECUTE IMMEDIATE 'CREATE UNIQUE INDEX UK_PA_TICKETS_USER_EMAIL_UPPER ON PA_TICKETS_USER (UPPER(S_EMAIL))';
    END IF;
END;
/
