-- Phase 7.4 PostgreSQL operational reliability fields for bounded durable job retries.
ALTER TABLE "PA_TICKETS_BACKGROUND_JOB"
  ADD COLUMN IF NOT EXISTS "N_MAX_ATTEMPTS" integer NOT NULL DEFAULT 5,
  ADD COLUMN IF NOT EXISTS "S_FAILURE_CLASSIFICATION" varchar(30),
  ADD COLUMN IF NOT EXISTS "D_FIRST_FAILED_AT" timestamptz,
  ADD COLUMN IF NOT EXISTS "D_LAST_ATTEMPT_AT" timestamptz,
  ADD COLUMN IF NOT EXISTS "D_FAILED_AT" timestamptz,
  ADD COLUMN IF NOT EXISTS "S_CORRELATION_ID" varchar(100);

UPDATE "PA_TICKETS_BACKGROUND_JOB" SET "N_MAX_ATTEMPTS" = 5 WHERE "N_MAX_ATTEMPTS" < 1;
CREATE INDEX IF NOT EXISTS "IX_PA_TICKETS_BG_LEASE_EXPIRY"
  ON "PA_TICKETS_BACKGROUND_JOB"("S_STATUS", "D_LOCKED_AT")
  WHERE "S_STATUS" = 'PROCESSING';
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_indexes WHERE indexname = 'IX_PA_TICKETS_BG_LEASE_EXPIRY') THEN
    RAISE EXCEPTION 'Durable job lease expiry index is missing.';
  END IF;
END $$;