-- Baseline 001 and migrations 002-005 remain untouched.
CREATE SEQUENCE PA_TICKETS_APPROVAL_DELEGATION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
ALTER TABLE PA_TICKETS_WORKFLOW_INSTANCE ADD (N_ROW_VERSION NUMBER(19) DEFAULT 0 NOT NULL);
ALTER TABLE PA_TICKETS_WORKFLOW_STEP_INSTANCE ADD (N_ROW_VERSION NUMBER(19) DEFAULT 0 NOT NULL, S_JOIN_RULE VARCHAR2(30));
ALTER TABLE PA_TICKETS_APPROVAL ADD (N_ROW_VERSION NUMBER(19) DEFAULT 0 NOT NULL, D_EXPIRES_AT TIMESTAMP WITH TIME ZONE);
ALTER TABLE PA_TICKETS_SLA ADD (N_ROW_VERSION NUMBER(19) DEFAULT 0 NOT NULL, D_PAUSED_AT TIMESTAMP WITH TIME ZONE, D_COMPLETED_AT TIMESTAMP WITH TIME ZONE);
CREATE TABLE PA_TICKETS_APPROVAL_DELEGATION (
    N_APPROVAL_DELEGATION_ID NUMBER(18) NOT NULL, N_APPROVAL_ID NUMBER(18) NOT NULL,
    N_ORIGINAL_APPROVER NUMBER(18) NOT NULL, N_DELEGATE_USER_ID NUMBER(18) NOT NULL,
    D_EFFECTIVE_FROM TIMESTAMP WITH TIME ZONE NOT NULL, D_EFFECTIVE_TO TIMESTAMP WITH TIME ZONE,
    S_REASON VARCHAR2(2000), N_CREATED_BY NUMBER(18) NOT NULL,
    D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PA_TICKETS_APPROVAL_DEL PRIMARY KEY (N_APPROVAL_DELEGATION_ID),
    CONSTRAINT FK_PA_TICKETS_APD_APPROVAL FOREIGN KEY (N_APPROVAL_ID) REFERENCES PA_TICKETS_APPROVAL(N_APPROVAL_ID),
    CONSTRAINT FK_PA_TICKETS_APD_ORIGINAL FOREIGN KEY (N_ORIGINAL_APPROVER) REFERENCES PA_TICKETS_USER(N_USER_ID),
    CONSTRAINT FK_PA_TICKETS_APD_DELEGATE FOREIGN KEY (N_DELEGATE_USER_ID) REFERENCES PA_TICKETS_USER(N_USER_ID),
    CONSTRAINT FK_PA_TICKETS_APD_CREATOR FOREIGN KEY (N_CREATED_BY) REFERENCES PA_TICKETS_USER(N_USER_ID),
    CONSTRAINT CK_PA_TICKETS_APD_USERS CHECK (N_ORIGINAL_APPROVER <> N_DELEGATE_USER_ID)
);
CREATE INDEX IX_PA_TICKETS_APD_APPROVAL ON PA_TICKETS_APPROVAL_DELEGATION(N_APPROVAL_ID, D_EFFECTIVE_FROM, D_EFFECTIVE_TO);
COMMIT;
