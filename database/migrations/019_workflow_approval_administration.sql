    N_REQUIRE_REQUESTER_SOD NUMBER(1) DEFAULT 1 NOT NULL,
    N_REQUIRE_CREATOR_SOD NUMBER(1) DEFAULT 1 NOT NULL,
    N_REQUIRE_EXECUTOR_SOD NUMBER(1) DEFAULT 1 NOT NULL,
