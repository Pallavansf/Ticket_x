    SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
     WHERE TABLE_NAME = 'PA_TICKETS_ROLE_PERMISSION' AND CONSTRAINT_NAME = 'CK_PA_TICKETS_RP_DATES';
