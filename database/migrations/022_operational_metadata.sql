DECLARE
    PROCEDURE advance_sequence(p_name VARCHAR2, p_target NUMBER) IS
        v_last_number NUMBER;
        v_increment NUMBER;
        v_ignored NUMBER;
    BEGIN
        SELECT LAST_NUMBER INTO v_last_number FROM USER_SEQUENCES WHERE SEQUENCE_NAME = UPPER(p_name);
        v_increment := p_target - v_last_number;
        IF v_increment > 0 THEN
            EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || p_name || ' INCREMENT BY ' || TO_CHAR(v_increment, 'FM999999999999999999999999');
            EXECUTE IMMEDIATE 'SELECT ' || p_name || '.NEXTVAL FROM DUAL' INTO v_ignored;
            EXECUTE IMMEDIATE 'ALTER SEQUENCE ' || p_name || ' INCREMENT BY 1';
        END IF;
    END;
    v_target NUMBER;
BEGIN
    SELECT NVL(MAX(N_STATUS_ID),0) + 1 INTO v_target FROM PA_TICKETS_STATUS;
    advance_sequence('PA_TICKETS_STATUS_SEQ',v_target);
    SELECT NVL(MAX(N_PRIORITY_ID),0) + 1 INTO v_target FROM PA_TICKETS_PRIORITY;
    advance_sequence('PA_TICKETS_PRIORITY_SEQ',v_target);
    SELECT NVL(MAX(N_STATUS_TRANSITION_ID),0) + 1 INTO v_target FROM PA_TICKETS_STATUS_TRANSITION;
    advance_sequence('PA_TICKETS_STATUS_TRANSITION_SEQ',v_target);
END;
