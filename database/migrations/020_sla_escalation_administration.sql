UPDATE PA_TICKETS_SLA_POLICY
   SET N_SLA_POLICY_VERSION_ID = NVL(N_SLA_POLICY_VERSION_ID, N_SLA_POLICY_ID),
       N_POLICY_ID = NVL(N_POLICY_ID, N_SLA_POLICY_ID),
       S_POLICY_CODE = NVL(S_POLICY_CODE, S_SLA_CODE),
       N_VERSION_NO = NVL(N_VERSION_NO, 1),
       D_EFFECTIVE_FROM = NVL(D_EFFECTIVE_FROM, SYSTIMESTAMP),
       S_STATUS = CASE WHEN N_ACTIVE = 1 THEN 'PUBLISHED' ELSE 'DRAFT' END;

INSERT INTO PA_TICKETS_SLA_POLICY_DEFINITION
    (N_POLICY_ID, S_POLICY_CODE, S_POLICY_NAME, N_ACTIVE, N_CREATED_BY)
SELECT p.N_POLICY_ID, MAX(p.S_POLICY_CODE), MAX(p.S_POLICY_CODE), 1, 0
  FROM PA_TICKETS_SLA_POLICY p
 WHERE NOT EXISTS (
       SELECT 1 FROM PA_TICKETS_SLA_POLICY_DEFINITION d WHERE d.N_POLICY_ID = p.N_POLICY_ID)
 GROUP BY p.N_POLICY_ID;

