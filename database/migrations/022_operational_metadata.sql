DECLARE
    PROCEDURE add_column_if_missing(p_table VARCHAR2, p_column VARCHAR2, p_type VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = UPPER(p_table) AND COLUMN_NAME = UPPER(p_column);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE ' || p_table || ' ADD (' || p_column || ' ' || p_type || ')';
        END IF;
    END;
    PROCEDURE add_fk_if_missing(p_table VARCHAR2, p_name VARCHAR2, p_ddl VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count FROM USER_CONSTRAINTS
         WHERE TABLE_NAME = UPPER(p_table) AND CONSTRAINT_NAME = UPPER(p_name);
        IF v_count = 0 THEN EXECUTE IMMEDIATE p_ddl; END IF;
    END;
BEGIN
    add_column_if_missing('PA_TICKETS_STATUS', 'N_ROW_VERSION', 'NUMBER(10) DEFAULT 0 NOT NULL');
    add_column_if_missing('PA_TICKETS_STATUS_TRANSITION', 'N_ROW_VERSION', 'NUMBER(10) DEFAULT 0 NOT NULL');
    add_column_if_missing('PA_TICKETS_PRIORITY', 'N_IS_DEFAULT', 'NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('PA_TICKETS_PRIORITY', 'N_ROW_VERSION', 'NUMBER(10) DEFAULT 0 NOT NULL');
    add_fk_if_missing('PA_TICKETS_STATUS_TRANSITION', 'FK_PA_TICKETS_ST_FROM',
        'ALTER TABLE PA_TICKETS_STATUS_TRANSITION ADD CONSTRAINT FK_PA_TICKETS_ST_FROM FOREIGN KEY (S_FROM_STATUS_CODE) REFERENCES PA_TICKETS_STATUS(S_STATUS_CODE)');
    add_fk_if_missing('PA_TICKETS_STATUS_TRANSITION', 'FK_PA_TICKETS_ST_TO',
        'ALTER TABLE PA_TICKETS_STATUS_TRANSITION ADD CONSTRAINT FK_PA_TICKETS_ST_TO FOREIGN KEY (S_TO_STATUS_CODE) REFERENCES PA_TICKETS_STATUS(S_STATUS_CODE)');
END;
