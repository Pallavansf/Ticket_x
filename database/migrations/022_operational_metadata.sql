MERGE INTO PA_TICKETS_STATUS target
USING (
    SELECT 1 id,'NEW' code,'New' name,1 initial,1 open_flag,0 closed_flag,0 cancelled,1 display_order FROM DUAL UNION ALL
    SELECT 2,'TRIAGE','Triage',0,1,0,0,2 FROM DUAL UNION ALL
    SELECT 3,'ASSIGNED','Assigned',0,1,0,0,3 FROM DUAL UNION ALL
    SELECT 4,'IN_PROGRESS','In Progress',0,1,0,0,4 FROM DUAL UNION ALL
    SELECT 5,'WAITING','Waiting',0,1,0,0,5 FROM DUAL UNION ALL
    SELECT 6,'PENDING_APPROVAL','Pending Approval',0,1,0,0,6 FROM DUAL UNION ALL
    SELECT 7,'RESOLVED','Resolved',0,1,0,0,7 FROM DUAL UNION ALL
    SELECT 8,'CLOSED','Closed',0,0,1,0,8 FROM DUAL UNION ALL
    SELECT 9,'CANCELLED','Cancelled',0,0,0,1,9 FROM DUAL UNION ALL
    SELECT 10,'REOPENED','Reopened',0,1,0,0,10 FROM DUAL
) source
ON (target.S_STATUS_CODE = source.code)
WHEN NOT MATCHED THEN INSERT
    (N_STATUS_ID,S_STATUS_CODE,S_STATUS_NAME,N_IS_INITIAL,N_IS_OPEN,N_IS_CLOSED,N_IS_CANCELLED,N_DISPLAY_ORDER,N_ACTIVE,N_CREATED_BY)
VALUES (source.id,source.code,source.name,source.initial,source.open_flag,source.closed_flag,source.cancelled,source.display_order,1,0);

MERGE INTO PA_TICKETS_PRIORITY target
USING (
    SELECT 1 id,'LOW' code,'Low' name,'Low business impact' description,1 level_no,1 display_order,0 is_default FROM DUAL UNION ALL
    SELECT 2,'MEDIUM','Medium','Normal business priority',2,2,1 FROM DUAL UNION ALL
    SELECT 3,'HIGH','High','High business impact',3,3,0 FROM DUAL UNION ALL
    SELECT 4,'CRITICAL','Critical','Critical business impact requiring immediate action',4,4,0 FROM DUAL
) source
ON (target.S_PRIORITY_CODE = source.code)
WHEN NOT MATCHED THEN INSERT
    (N_PRIORITY_ID,S_PRIORITY_CODE,S_PRIORITY_NAME,S_DESCRIPTION,N_PRIORITY_LEVEL,N_DISPLAY_ORDER,N_ACTIVE,N_IS_DEFAULT,N_CREATED_BY)
VALUES (source.id,source.code,source.name,source.description,source.level_no,source.display_order,1,source.is_default,0);

UPDATE PA_TICKETS_PRIORITY SET N_IS_DEFAULT = 0, N_ROW_VERSION = N_ROW_VERSION + 1
 WHERE N_IS_DEFAULT = 1 AND N_PRIORITY_ID <> (SELECT MIN(N_PRIORITY_ID) FROM PA_TICKETS_PRIORITY WHERE N_IS_DEFAULT = 1);
UPDATE PA_TICKETS_PRIORITY SET N_IS_DEFAULT = 1, N_ROW_VERSION = N_ROW_VERSION + 1
 WHERE S_PRIORITY_CODE = 'MEDIUM' AND NOT EXISTS (SELECT 1 FROM PA_TICKETS_PRIORITY WHERE N_IS_DEFAULT = 1);

MERGE INTO PA_TICKETS_STATUS_TRANSITION target
USING (
    SELECT 'NEW' src,'TRIAGE' dst FROM DUAL UNION ALL
    SELECT 'NEW','CANCELLED' FROM DUAL UNION ALL
    SELECT 'TRIAGE','ASSIGNED' FROM DUAL UNION ALL
    SELECT 'TRIAGE','CANCELLED' FROM DUAL UNION ALL
    SELECT 'ASSIGNED','IN_PROGRESS' FROM DUAL UNION ALL
    SELECT 'ASSIGNED','PENDING_APPROVAL' FROM DUAL UNION ALL
    SELECT 'ASSIGNED','CANCELLED' FROM DUAL UNION ALL
    SELECT 'PENDING_APPROVAL','ASSIGNED' FROM DUAL UNION ALL
    SELECT 'PENDING_APPROVAL','CANCELLED' FROM DUAL UNION ALL
    SELECT 'IN_PROGRESS','WAITING' FROM DUAL UNION ALL
    SELECT 'IN_PROGRESS','RESOLVED' FROM DUAL UNION ALL
    SELECT 'IN_PROGRESS','CANCELLED' FROM DUAL UNION ALL
    SELECT 'WAITING','IN_PROGRESS' FROM DUAL UNION ALL
    SELECT 'WAITING','RESOLVED' FROM DUAL UNION ALL
    SELECT 'WAITING','CANCELLED' FROM DUAL UNION ALL
    SELECT 'RESOLVED','CLOSED' FROM DUAL UNION ALL
    SELECT 'RESOLVED','REOPENED' FROM DUAL UNION ALL
    SELECT 'CLOSED','REOPENED' FROM DUAL UNION ALL
    SELECT 'REOPENED','TRIAGE' FROM DUAL UNION ALL
    SELECT 'REOPENED','ASSIGNED' FROM DUAL UNION ALL
    SELECT 'REOPENED','CANCELLED' FROM DUAL
) source
ON (target.S_FROM_STATUS_CODE = source.src AND target.S_TO_STATUS_CODE = source.dst)
WHEN NOT MATCHED THEN INSERT
    (N_STATUS_TRANSITION_ID,S_FROM_STATUS_CODE,S_TO_STATUS_CODE,N_ALLOWED,N_CREATED_BY)
VALUES (PA_TICKETS_STATUS_TRANSITION_SEQ.NEXTVAL,source.src,source.dst,1,0);

