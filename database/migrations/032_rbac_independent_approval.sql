-- PA TICKETS Oracle migration 032.
-- Adds durable two-person proposals for sensitive role-permission grants only.
-- Oracle commits DDL implicitly. Review and rehearse recovery before an approved deployment.
-- This draft is intentionally unexecuted.

DECLARE
    v_count NUMBER;
    PROCEDURE create_index_if_missing(p_name VARCHAR2, p_sql VARCHAR2) IS
        v_index_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_index_count FROM USER_INDEXES WHERE INDEX_NAME = UPPER(p_name);
        IF v_index_count = 0 THEN
            EXECUTE IMMEDIATE p_sql;
        END IF;
    END;
BEGIN
    SELECT COUNT(*) INTO v_count FROM USER_TABLES WHERE TABLE_NAME = 'PA_TICKETS_RBAC_PROPOSAL';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE q'[
            CREATE TABLE PA_TICKETS_RBAC_PROPOSAL (
                S_PROPOSAL_ID VARCHAR2(32) NOT NULL,
                S_OPERATION_TYPE VARCHAR2(40) NOT NULL,
                S_STATUS VARCHAR2(20) NOT NULL,
                N_TARGET_ROLE_ID NUMBER(18) NOT NULL,
                N_TARGET_PERMISSION_ID NUMBER(18) NOT NULL,
                N_INITIATOR_USER_ID NUMBER(18) NOT NULL,
                D_CREATED_AT TIMESTAMP WITH TIME ZONE NOT NULL,
                D_EXPIRES_AT TIMESTAMP WITH TIME ZONE NOT NULL,
                S_REASON VARCHAR2(1000) NOT NULL,
                S_IDEMPOTENCY_KEY VARCHAR2(100) NOT NULL,
                S_PAYLOAD_JSON CLOB NOT NULL,
                S_PAYLOAD_SHA256 CHAR(64) NOT NULL,
                N_APPROVER_USER_ID NUMBER(18),
                N_CANCELLED_BY_USER_ID NUMBER(18),
                D_DECISION_AT TIMESTAMP WITH TIME ZONE,
                S_DECISION_REASON VARCHAR2(1000),
                S_APPLICATION_OUTCOME VARCHAR2(80),
                S_CORRELATION_ID VARCHAR2(100) NOT NULL,
                N_ROW_VERSION NUMBER(10) NOT NULL,
                CONSTRAINT PK_PA_TICKETS_RBAC_PROPOSAL PRIMARY KEY (S_PROPOSAL_ID),
                CONSTRAINT CK_PA_TICKETS_RBAC_PROPOSAL_ID CHECK (LENGTH(S_PROPOSAL_ID) = 32),
                CONSTRAINT CK_PA_TICKETS_RBAC_PROPOSAL_OP CHECK (S_OPERATION_TYPE = 'ROLE_PERMISSION_GRANT'),
                CONSTRAINT CK_PA_TICKETS_RBAC_PROPOSAL_STATUS
                    CHECK (S_STATUS IN ('PENDING','APPROVED','REJECTED','APPLIED','EXPIRED','CANCELLED')),
                CONSTRAINT CK_PA_TICKETS_RBAC_PROPOSAL_DATES CHECK (D_EXPIRES_AT > D_CREATED_AT),
                CONSTRAINT CK_PA_TICKETS_RBAC_PROPOSAL_VERSION CHECK (N_ROW_VERSION > 0),
                CONSTRAINT FK_PA_TICKETS_RBAC_PROPOSAL_ROLE FOREIGN KEY (N_TARGET_ROLE_ID)
                    REFERENCES PA_TICKETS_ROLE (N_ROLE_ID),
                CONSTRAINT FK_PA_TICKETS_RBAC_PROPOSAL_PERMISSION FOREIGN KEY (N_TARGET_PERMISSION_ID)
                    REFERENCES PA_TICKETS_PERMISSION (N_PERMISSION_ID),
                CONSTRAINT FK_PA_TICKETS_RBAC_PROPOSAL_INITIATOR FOREIGN KEY (N_INITIATOR_USER_ID)
                    REFERENCES PA_TICKETS_USER (N_USER_ID),
                CONSTRAINT FK_PA_TICKETS_RBAC_PROPOSAL_APPROVER FOREIGN KEY (N_APPROVER_USER_ID)
                    REFERENCES PA_TICKETS_USER (N_USER_ID),
                CONSTRAINT FK_PA_TICKETS_RBAC_PROPOSAL_CANCELLER FOREIGN KEY (N_CANCELLED_BY_USER_ID)
                    REFERENCES PA_TICKETS_USER (N_USER_ID)
            )
        ]';
    END IF;

    create_index_if_missing('UX_PA_TICKETS_RBAC_PROPOSAL_IDEMPOTENCY',
        'CREATE UNIQUE INDEX UX_PA_TICKETS_RBAC_PROPOSAL_IDEMPOTENCY ON PA_TICKETS_RBAC_PROPOSAL (N_INITIATOR_USER_ID, S_IDEMPOTENCY_KEY)');
    create_index_if_missing('IX_PA_TICKETS_RBAC_PROPOSAL_QUEUE',
        'CREATE INDEX IX_PA_TICKETS_RBAC_PROPOSAL_QUEUE ON PA_TICKETS_RBAC_PROPOSAL (S_STATUS, D_EXPIRES_AT, D_CREATED_AT)');
    create_index_if_missing('IX_PA_TICKETS_RBAC_PROPOSAL_INITIATOR',
        'CREATE INDEX IX_PA_TICKETS_RBAC_PROPOSAL_INITIATOR ON PA_TICKETS_RBAC_PROPOSAL (N_INITIATOR_USER_ID, D_CREATED_AT)');
END;
