-- PA_TICKETS RBAC migration 035 (REVIEW DRAFT; do not execute without approval).
-- Purpose: add explicit membership scopes and Admin Head delegation.
-- No scope rows are inserted. ORGANIZATION means NULL organization ID in this single-org model.
-- Client foreign keys are intentionally deferred until client ID 872002 semantics are approved.
-- Prerequisite: verified baseline, 033 ledger, and parent role/user/membership relations.

BEGIN;

DO $$
BEGIN
    IF to_regclass('"PA_TICKETS_USER_ROLE"') IS NULL
       OR to_regclass('"PA_TICKETS_ROLE"') IS NULL
       OR to_regclass('"PA_TICKETS_USER"') IS NULL THEN
        RAISE EXCEPTION 'RBAC migration 035 blocked: user, role, or membership relation is absent';
    END IF;
END $$;

CREATE SEQUENCE IF NOT EXISTS "PA_TICKETS_ROLE_SCOPE_SEQ" START WITH 1 INCREMENT BY 1;
CREATE SEQUENCE IF NOT EXISTS "PA_TICKETS_ADMIN_DELEGATION_SEQ" START WITH 1 INCREMENT BY 1;

CREATE TABLE IF NOT EXISTS "PA_TICKETS_USER_ROLE_SCOPE" (
    "N_ROLE_SCOPE_ID" bigint NOT NULL,
    "N_USER_ROLE_ID" bigint NOT NULL,
    "S_SCOPE_TYPE" varchar(30) NOT NULL,
    "N_ORGANIZATION_ID" bigint,
    "N_DEPARTMENT_ID" bigint,
    "N_TEAM_ID" bigint,
    "N_CLIENT_ID" bigint,
    "S_RESOURCE_TYPE" varchar(100),
    "S_RESOURCE_ID" varchar(300),
    "D_VALID_FROM" timestamptz NOT NULL,
    "D_VALID_TO" timestamptz,
    "N_ACTIVE" boolean NOT NULL DEFAULT true,
    "D_CREATED_AT" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "N_CREATED_BY" bigint NOT NULL,
    CONSTRAINT "PK_PA_TICKETS_ROLE_SCOPE" PRIMARY KEY ("N_ROLE_SCOPE_ID"),
    CONSTRAINT "FK_PA_TICKETS_ROLE_SCOPE_MEMBERSHIP" FOREIGN KEY ("N_USER_ROLE_ID")
        REFERENCES "PA_TICKETS_USER_ROLE" ("N_USER_ROLE_ID"),
    CONSTRAINT "CK_PA_TICKETS_ROLE_SCOPE_TYPE" CHECK
        ("S_SCOPE_TYPE" IN ('ORGANIZATION','DEPARTMENT','TEAM','CLIENT','ADMIN_GROUP','RECORD')),
    CONSTRAINT "CK_PA_TICKETS_ROLE_SCOPE_ORG_SENTINEL" CHECK
        ("S_SCOPE_TYPE" <> 'ORGANIZATION' OR "N_ORGANIZATION_ID" IS NULL),
    CONSTRAINT "CK_PA_TICKETS_ROLE_SCOPE_DATES" CHECK
        ("D_VALID_TO" IS NULL OR "D_VALID_TO" > "D_VALID_FROM")
);

CREATE INDEX IF NOT EXISTS "IX_PA_TICKETS_ROLE_SCOPE_EFFECTIVE"
    ON "PA_TICKETS_USER_ROLE_SCOPE"
       ("N_USER_ROLE_ID", "S_SCOPE_TYPE", "N_ACTIVE", "D_VALID_FROM", "D_VALID_TO");

CREATE TABLE IF NOT EXISTS "PA_TICKETS_ADMIN_HEAD_DELEGATION" (
    "N_ADMIN_DELEGATION_ID" bigint NOT NULL,
    "N_ADMIN_HEAD_USER_ID" bigint NOT NULL,
    "N_ADMIN_USER_ID" bigint NOT NULL,
    "D_VALID_FROM" timestamptz NOT NULL,
    "D_VALID_TO" timestamptz,
    "N_ACTIVE" boolean NOT NULL DEFAULT true,
    "D_CREATED_AT" timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    "N_CREATED_BY" bigint NOT NULL,
    CONSTRAINT "PK_PA_TICKETS_ADMIN_DELEGATION" PRIMARY KEY ("N_ADMIN_DELEGATION_ID"),
    CONSTRAINT "FK_PA_TICKETS_ADMIN_DELEGATION_HEAD" FOREIGN KEY ("N_ADMIN_HEAD_USER_ID")
        REFERENCES "PA_TICKETS_USER" ("N_USER_ID"),
    CONSTRAINT "FK_PA_TICKETS_ADMIN_DELEGATION_ADMIN" FOREIGN KEY ("N_ADMIN_USER_ID")
        REFERENCES "PA_TICKETS_USER" ("N_USER_ID"),
    CONSTRAINT "CK_PA_TICKETS_ADMIN_DELEGATION_DATES" CHECK
        ("D_VALID_TO" IS NULL OR "D_VALID_TO" > "D_VALID_FROM"),
    CONSTRAINT "UK_PA_TICKETS_ADMIN_DELEGATION_START" UNIQUE
        ("N_ADMIN_HEAD_USER_ID", "N_ADMIN_USER_ID", "D_VALID_FROM")
);

CREATE INDEX IF NOT EXISTS "IX_PA_TICKETS_ADMIN_DELEGATION_EFFECTIVE"
    ON "PA_TICKETS_ADMIN_HEAD_DELEGATION"
       ("N_ADMIN_HEAD_USER_ID", "N_ADMIN_USER_ID", "N_ACTIVE", "D_VALID_FROM", "D_VALID_TO");

COMMIT;
