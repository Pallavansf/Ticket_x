DECLARE
    column_count NUMBER;
BEGIN
    SELECT COUNT(*)
      INTO column_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'PA_TICKETS_USER'
       AND COLUMN_NAME = 'S_PASSWORD_HASH';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PA_TICKETS_USER ADD (S_PASSWORD_HASH VARCHAR2(500))';
    END IF;

    SELECT COUNT(*)
      INTO column_count
      FROM USER_TAB_COLUMNS
     WHERE TABLE_NAME = 'PA_TICKETS_USER'
       AND COLUMN_NAME = 'N_PASSWORD_ROTATION_REQUIRED';

    IF column_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PA_TICKETS_USER ADD (N_PASSWORD_ROTATION_REQUIRED NUMBER(1) DEFAULT 0 NOT NULL)';
    END IF;
END;
/
