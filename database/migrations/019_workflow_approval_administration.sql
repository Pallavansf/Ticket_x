    D_PUBLISHED_AT TIMESTAMP WITH TIME ZONE,
    N_PUBLISHED_BY NUMBER(18),
    D_RETIRED_AT TIMESTAMP WITH TIME ZONE,
    N_RETIRED_BY NUMBER(18),
    N_ROW_VERSION NUMBER(19) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PA_TICKETS_APPROVAL_RULE_VERSION PRIMARY KEY (N_APPROVAL_RULE_VERSION_ID),
    CONSTRAINT FK_PA_TICKETS_APRV_RULE FOREIGN KEY (N_APPROVAL_RULE_ID) REFERENCES PA_TICKETS_APPROVAL_RULE(N_APPROVAL_RULE_ID),
    CONSTRAINT UK_PA_TICKETS_APRV_NO UNIQUE (N_APPROVAL_RULE_ID, N_VERSION_NO),
    CONSTRAINT UK_PA_TICKETS_APRV_ID_RULE UNIQUE (N_APPROVAL_RULE_VERSION_ID, N_APPROVAL_RULE_ID),
    CONSTRAINT CK_PA_TICKETS_APRV_STATUS CHECK (S_STATUS IN ('DRAFT','PUBLISHED','RETIRED')),
    CONSTRAINT CK_PA_TICKETS_APRV_MODE CHECK (S_MODE IN ('ANY_ONE','ALL_REQUIRED','SEQUENTIAL')),
    CONSTRAINT CK_PA_TICKETS_APRV_REJECT CHECK (S_REJECTION_BEHAVIOR IN ('REJECT','CANCEL')),
    CONSTRAINT CK_PA_TICKETS_APRV_FLAGS CHECK (N_DELEGATION_ALLOWED IN (0,1) AND N_REQUIRE_REQUESTER_SOD IN (0,1) AND N_REQUIRE_CREATOR_SOD IN (0,1) AND N_REQUIRE_EXECUTOR_SOD IN (0,1)),
    CONSTRAINT CK_PA_TICKETS_APRV_DATES CHECK (D_EFFECTIVE_TO IS NULL OR D_EFFECTIVE_TO > D_EFFECTIVE_FROM),
    CONSTRAINT CK_PA_TICKETS_APRV_EXPIRY CHECK (N_EXPIRY_MINUTES IS NULL OR N_EXPIRY_MINUTES > 0)
);

