);

DECLARE
    PROCEDURE add_column_if_missing(p_name VARCHAR2, p_type VARCHAR2) IS
        v_count NUMBER;
    BEGIN
        SELECT COUNT(*) INTO v_count
          FROM USER_TAB_COLUMNS
         WHERE TABLE_NAME = 'PA_TICKETS_SLA_POLICY'
           AND COLUMN_NAME = UPPER(p_name);
        IF v_count = 0 THEN
            EXECUTE IMMEDIATE 'ALTER TABLE PA_TICKETS_SLA_POLICY ADD (' || p_name || ' ' || p_type || ')';
        END IF;
    END;
BEGIN
    add_column_if_missing('N_SLA_POLICY_VERSION_ID', 'NUMBER(18)');
    add_column_if_missing('N_POLICY_ID', 'NUMBER(18)');
    add_column_if_missing('S_POLICY_CODE', 'VARCHAR2(100)');
    add_column_if_missing('N_VERSION_NO', 'NUMBER(10)');
    add_column_if_missing('N_ACTIVE', 'NUMBER(1) DEFAULT 0 NOT NULL');
    add_column_if_missing('D_EFFECTIVE_FROM', 'TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('D_EFFECTIVE_TO', 'TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('N_SERVICE_ID', 'NUMBER(18)');
    add_column_if_missing('N_REQUEST_TYPE_ID', 'NUMBER(18)');
    add_column_if_missing('N_PRIORITY_ID', 'NUMBER(18)');
    add_column_if_missing('N_CLIENT_ID', 'NUMBER(18)');
    add_column_if_missing('N_DEPARTMENT_ID', 'NUMBER(18)');
    add_column_if_missing('N_TEAM_ID', 'NUMBER(18)');
    add_column_if_missing('N_TICKET_TYPE', 'NUMBER(10)');
    add_column_if_missing('N_CATEGORY_ID', 'NUMBER(18)');
    add_column_if_missing('N_SUB_CATEGORY_ID', 'NUMBER(18)');
    add_column_if_missing('N_RESPONSE_TARGET_MINUTES', 'NUMBER(10)');
    add_column_if_missing('N_RESOLUTION_TARGET_MINUTES', 'NUMBER(10)');
    add_column_if_missing('S_CALENDAR_CODE', 'VARCHAR2(100) DEFAULT ''DEFAULT''');
    add_column_if_missing('S_WAITING_RULES', 'CLOB');
    add_column_if_missing('S_PAUSE_RULES', 'CLOB');
    add_column_if_missing('S_ESCALATION_RULES', 'CLOB');
    add_column_if_missing('S_BREACH_RULES', 'CLOB');
    add_column_if_missing('S_NOTIFICATION_RULES', 'CLOB');
    add_column_if_missing('S_STATUS', 'VARCHAR2(20) DEFAULT ''DRAFT'' NOT NULL');
    add_column_if_missing('D_CREATED_AT', 'TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL');
    add_column_if_missing('N_CREATED_BY', 'NUMBER(18) DEFAULT 0 NOT NULL');
    add_column_if_missing('D_PUBLISHED_AT', 'TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('N_PUBLISHED_BY', 'NUMBER(18)');
    add_column_if_missing('D_RETIRED_AT', 'TIMESTAMP WITH TIME ZONE');
    add_column_if_missing('N_RETIRED_BY', 'NUMBER(18)');
    add_column_if_missing('N_ROW_VERSION', 'NUMBER(10) DEFAULT 0 NOT NULL');
END;
