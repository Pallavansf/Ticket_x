    N_CREATED_BY NUMBER(18) NOT NULL,
    N_ROW_VERSION NUMBER(10) DEFAULT 0 NOT NULL,
    CONSTRAINT PK_PA_TICKETS_SLA_POLICY_DEF PRIMARY KEY (N_POLICY_ID),
