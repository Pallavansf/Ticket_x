-- PA TICKETS additive migration 005: communication, auth/MFA, and SLA foundations
-- Baseline 001 and migrations 002-004 remain untouched.

CREATE SEQUENCE PA_TICKETS_AUTH_PROVIDER_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PA_TICKETS_MFA_ENROLLMENT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PA_TICKETS_MFA_POLICY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;

ALTER TABLE PA_TICKETS_COMMUNICATION ADD (
    S_CHANNEL VARCHAR2(30), S_PROVIDER_CODE VARCHAR2(100), S_TEMPLATE_CODE VARCHAR2(200),
    S_STRUCTURED_PAYLOAD CLOB, S_STATUS VARCHAR2(30) DEFAULT 'RECORDED' NOT NULL,
    N_RETRY_COUNT NUMBER(10) DEFAULT 0 NOT NULL, S_FAILURE_REASON VARCHAR2(2000),
    S_PROVIDER_MESSAGE_ID VARCHAR2(500), D_SCHEDULED_AT TIMESTAMP WITH TIME ZONE,
    D_SENT_AT TIMESTAMP WITH TIME ZONE, D_DELIVERED_AT TIMESTAMP WITH TIME ZONE,
    D_READ_AT TIMESTAMP WITH TIME ZONE, S_CORRELATION_ID VARCHAR2(100)
);
ALTER TABLE PA_TICKETS_COMMUNICATION ADD CONSTRAINT CK_PA_TICKETS_COMM_STATUS
    CHECK (S_STATUS IN ('PENDING','SENT','FAILED','DELIVERED','READ','RECORDED'));
CREATE INDEX IX_PA_TICKETS_COMM_STATUS ON PA_TICKETS_COMMUNICATION(S_STATUS, D_SCHEDULED_AT);

CREATE TABLE PA_TICKETS_AUTH_PROVIDER (
    N_AUTH_PROVIDER_ID NUMBER(18) NOT NULL, S_PROVIDER_CODE VARCHAR2(100) NOT NULL,
    S_PROVIDER_TYPE VARCHAR2(30) NOT NULL, S_ISSUER_OR_AUTHORITY VARCHAR2(1000),
    S_CLIENT_ID VARCHAR2(500), S_SCOPES VARCHAR2(2000), S_CLAIMS_MAPPING CLOB,
    S_ROLE_MAPPING CLOB, S_SECRET_REFERENCE VARCHAR2(1000), N_ENABLED NUMBER(1) DEFAULT 0 NOT NULL,
    D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, N_CREATED_BY NUMBER(18) NOT NULL,
    D_UPDATED_AT TIMESTAMP WITH TIME ZONE, N_UPDATED_BY NUMBER(18),
    CONSTRAINT PK_PA_TICKETS_AUTH_PROVIDER PRIMARY KEY (N_AUTH_PROVIDER_ID),
    CONSTRAINT UK_PA_TICKETS_AUTH_PROVIDER UNIQUE (S_PROVIDER_CODE),
    CONSTRAINT CK_PA_TICKETS_AUTH_TYPE CHECK (S_PROVIDER_TYPE IN ('OIDC','SAML')),
    CONSTRAINT CK_PA_TICKETS_AUTH_ENABLED CHECK (N_ENABLED IN (0,1))
);

CREATE TABLE PA_TICKETS_MFA_POLICY (
    N_MFA_POLICY_ID NUMBER(18) NOT NULL, S_POLICY_CODE VARCHAR2(100) NOT NULL,
    S_MODE VARCHAR2(20) NOT NULL, S_SCOPE_RULE CLOB, N_ACTIVE NUMBER(1) DEFAULT 1 NOT NULL,
    D_EFFECTIVE_FROM TIMESTAMP WITH TIME ZONE NOT NULL, D_EFFECTIVE_TO TIMESTAMP WITH TIME ZONE,
    D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL, N_CREATED_BY NUMBER(18) NOT NULL,
    CONSTRAINT PK_PA_TICKETS_MFA_POLICY PRIMARY KEY (N_MFA_POLICY_ID),
    CONSTRAINT UK_PA_TICKETS_MFA_POLICY UNIQUE (S_POLICY_CODE),
    CONSTRAINT CK_PA_TICKETS_MFA_MODE CHECK (S_MODE IN ('DISABLED','OPTIONAL','REQUIRED')),
    CONSTRAINT CK_PA_TICKETS_MFA_ACTIVE CHECK (N_ACTIVE IN (0,1))
);

CREATE TABLE PA_TICKETS_MFA_ENROLLMENT (
    N_MFA_ENROLLMENT_ID NUMBER(18) NOT NULL, N_USER_ID NUMBER(18) NOT NULL,
    S_METHOD VARCHAR2(30) DEFAULT 'TOTP' NOT NULL, S_PROTECTED_SECRET CLOB,
    S_SECRET_REFERENCE VARCHAR2(1000), S_STATUS VARCHAR2(30) DEFAULT 'ENROLLED' NOT NULL,
    D_ENROLLED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    D_LAST_USED_AT TIMESTAMP WITH TIME ZONE, D_DISABLED_AT TIMESTAMP WITH TIME ZONE,
    N_CREATED_BY NUMBER(18) NOT NULL,
    CONSTRAINT PK_PA_TICKETS_MFA_ENROLL PRIMARY KEY (N_MFA_ENROLLMENT_ID),
    CONSTRAINT FK_PA_TICKETS_MFA_USER FOREIGN KEY (N_USER_ID) REFERENCES PA_TICKETS_USER(N_USER_ID),
    CONSTRAINT CK_PA_TICKETS_MFA_METHOD CHECK (S_METHOD IN ('TOTP','SSO_DELEGATED')),
    CONSTRAINT CK_PA_TICKETS_MFA_STATUS CHECK (S_STATUS IN ('ENROLLED','ENABLED','DISABLED','RECOVERY'))
);
CREATE UNIQUE INDEX UX_PA_TICKETS_MFA_ACTIVE ON PA_TICKETS_MFA_ENROLLMENT
    (CASE WHEN S_STATUS IN ('ENROLLED','ENABLED') THEN N_USER_ID END, CASE WHEN S_STATUS IN ('ENROLLED','ENABLED') THEN S_METHOD END);

ALTER TABLE PA_TICKETS_SLA_POLICY ADD (
    N_VERSION_NO NUMBER(10) DEFAULT 1 NOT NULL, D_EFFECTIVE_FROM TIMESTAMP WITH TIME ZONE,
    D_EFFECTIVE_TO TIMESTAMP WITH TIME ZONE, S_WAITING_RULES CLOB, S_PAUSE_RULES CLOB,
    S_ESCALATION_RULES CLOB, S_BREACH_RULES CLOB, S_NOTIFICATION_RULES CLOB,
    S_TARGETING_RULE CLOB
);
ALTER TABLE PA_TICKETS_SLA ADD (N_SLA_POLICY_VERSION NUMBER(10));
ALTER TABLE PA_TICKETS_REQUEST_SLA ADD (
    N_SERVICE_ID NUMBER(18), N_CATEGORY_ID NUMBER(18), N_TICKET_TYPE_ID NUMBER(18),
    N_DEPARTMENT_ID NUMBER(18), N_TEAM_ID NUMBER(18), N_CLIENT_ID NUMBER(18), N_POLICY_VERSION_NO NUMBER(10)
);
ALTER TABLE PA_TICKETS_REQUEST_SLA ADD CONSTRAINT FK_PA_TICKETS_RS_SERVICE FOREIGN KEY (N_SERVICE_ID) REFERENCES PA_TICKETS_SERVICE(N_SERVICE_ID);
ALTER TABLE PA_TICKETS_REQUEST_SLA ADD CONSTRAINT FK_PA_TICKETS_RS_CATEGORY FOREIGN KEY (N_CATEGORY_ID) REFERENCES PA_TICKETS_CATEGORY(N_CATEGORY_ID);
ALTER TABLE PA_TICKETS_REQUEST_SLA ADD CONSTRAINT FK_PA_TICKETS_RS_TYPE FOREIGN KEY (N_TICKET_TYPE_ID) REFERENCES PA_TICKETS_TYPE(N_TICKET_TYPE_ID);
ALTER TABLE PA_TICKETS_REQUEST_SLA ADD CONSTRAINT FK_PA_TICKETS_RS_DEPT FOREIGN KEY (N_DEPARTMENT_ID) REFERENCES PA_TICKETS_DEPARTMENT(N_DEPARTMENT_ID);
ALTER TABLE PA_TICKETS_REQUEST_SLA ADD CONSTRAINT FK_PA_TICKETS_RS_TEAM FOREIGN KEY (N_TEAM_ID) REFERENCES PA_TICKETS_TEAM(N_TEAM_ID);
ALTER TABLE PA_TICKETS_REQUEST_SLA ADD CONSTRAINT FK_PA_TICKETS_RS_CLIENT FOREIGN KEY (N_CLIENT_ID) REFERENCES PA_TICKETS_CLIENT(N_CLIENT_ID);
CREATE INDEX IX_PA_TICKETS_SLA_POLICY_VERSION ON PA_TICKETS_SLA_POLICY(S_SLA_CODE, N_VERSION_NO, D_EFFECTIVE_FROM);
COMMIT;
