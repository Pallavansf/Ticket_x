
-- ============================================================
-- PA TICKETS - ORACLE DATABASE SCHEMA
-- Purpose:
--   Enterprise internal work-management / ticketing platform
--   for Requests, Incidents, Problems, Tasks and Changes.
--
-- Naming:
--   PA_TICKETS*  : database objects
--   S_           : string / character
--   N_           : number
--   D_           : date / timestamp
--
-- Time:
--   Business/application timezone: Asia/Kolkata (IST)
--   D_* timestamp columns use TIMESTAMP WITH TIME ZONE.
--
-- Design principles:
--   - One organization, not multi-tenant.
--   - Client is a business entity, not a tenant.
--   - OPS is a requester/business-side actor.
--   - Ticket is the business record.
--   - Work items represent executable/routed work within a ticket.
--   - Workflow, approval, SLA and audit are first-class.
--   - Historical/audit records are append-only from the application.
--   - No ordinary delete of audit/evidence history.
-- ============================================================

