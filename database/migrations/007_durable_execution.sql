-- PA TICKETS additive migration 007: durable idempotency and background execution
-- Baseline 001 and migrations 002-006 remain untouched.
CREATE SEQUENCE PA_TICKETS_IDEMPOTENCY_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE PA_TICKETS_BACKGROUND_JOB_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
ALTER TABLE PA_TICKETS_WORKFLOW_STEP_INSTANCE_HISTORY ADD (S_CORRELATION_ID VARCHAR2(100), S_IDEMPOTENCY_KEY VARCHAR2(200));
ALTER TABLE PA_TICKETS_APPROVAL_HISTORY ADD (S_CORRELATION_ID VARCHAR2(100), S_IDEMPOTENCY_KEY VARCHAR2(200));
ALTER TABLE PA_TICKETS_COMMUNICATION ADD (S_IDEMPOTENCY_KEY VARCHAR2(200), D_NEXT_RETRY_AT TIMESTAMP WITH TIME ZONE);
CREATE TABLE PA_TICKETS_IDEMPOTENCY (
    N_IDEMPOTENCY_ID NUMBER(18) NOT NULL, S_SCOPE VARCHAR2(100) NOT NULL, S_IDEMPOTENCY_KEY VARCHAR2(200) NOT NULL,
    S_STATUS VARCHAR2(30) NOT NULL, S_RESPONSE_HASH VARCHAR2(128), D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    D_COMPLETED_AT TIMESTAMP WITH TIME ZONE, CONSTRAINT PK_PA_TICKETS_IDEMPOTENCY PRIMARY KEY (N_IDEMPOTENCY_ID),
    CONSTRAINT UK_PA_TICKETS_IDEMPOTENCY UNIQUE (S_SCOPE,S_IDEMPOTENCY_KEY),
    CONSTRAINT CK_PA_TICKETS_IDEMPOTENCY_STATUS CHECK (S_STATUS IN ('PROCESSING','COMPLETED','FAILED'))
);
CREATE TABLE PA_TICKETS_BACKGROUND_JOB (
    N_BACKGROUND_JOB_ID NUMBER(18) NOT NULL, S_JOB_TYPE VARCHAR2(100) NOT NULL, S_DEDUPE_KEY VARCHAR2(200) NOT NULL,
    S_PAYLOAD CLOB, S_STATUS VARCHAR2(30) DEFAULT 'PENDING' NOT NULL, N_ATTEMPT_COUNT NUMBER(10) DEFAULT 0 NOT NULL,
    D_SCHEDULED_AT TIMESTAMP WITH TIME ZONE NOT NULL, D_NEXT_ATTEMPT_AT TIMESTAMP WITH TIME ZONE,
    D_LOCKED_AT TIMESTAMP WITH TIME ZONE, S_LOCKED_BY VARCHAR2(200), S_LAST_ERROR VARCHAR2(2000),
    D_COMPLETED_AT TIMESTAMP WITH TIME ZONE, D_CREATED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT PK_PA_TICKETS_BG_JOB PRIMARY KEY (N_BACKGROUND_JOB_ID),
    CONSTRAINT UK_PA_TICKETS_BG_DEDUPE UNIQUE (S_JOB_TYPE,S_DEDUPE_KEY),
    CONSTRAINT CK_PA_TICKETS_BG_STATUS CHECK (S_STATUS IN ('PENDING','PROCESSING','COMPLETED','FAILED','EXHAUSTED'))
);
CREATE INDEX IX_PA_TICKETS_BG_READY ON PA_TICKETS_BACKGROUND_JOB(S_STATUS,D_NEXT_ATTEMPT_AT,D_SCHEDULED_AT);
COMMIT;
